<?php
/**
 * Dotted world map rendered from a coarse ASCII mask (equirectangular, 64x28).
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$mc_map = array(
	'                                                                ',
	'              ####         ###                                  ',
	'     #########################         ##   ######## ####       ',
	'  ######################  ###        #### ####################  ',
	' ####################### ##        ##  ###########################',
	'   #################### ##          ##########################  ',
	'     ##################            ###########################  ',
	'      ################           ############################   ',
	'       ##############            ########################  #    ',
	'        ###########              ######## ###############       ',
	'         ########               ####    ##  ##########   #      ',
	'           ####  #             ##########    #########          ',
	'             ###               ###########    ### ####          ',
	'              #####            ############    #   ##           ',
	'               #######          ##########          ##  #       ',
	'               #########          #######            ### ##     ',
	'               ##########          ######              ####     ',
	'                #########          #######              #       ',
	'                 #######           ######           ######      ',
	'                  #####             ####           ########     ',
	'                  ####              ###            #########    ',
	'                  ###                ##             #######     ',
	'                  ##                                  ##     #  ',
	'                  ##                                        #   ',
	'                   #                                            ',
	'                                                                ',
);

$mc_step = 4;
$mc_w    = 64 * $mc_step;
$mc_h    = count( $mc_map ) * $mc_step;
?>
<svg class="mc-world" viewBox="0 0 <?php echo (int) $mc_w; ?> <?php echo (int) $mc_h; ?>" aria-hidden="true" focusable="false">
	<?php
	foreach ( $mc_map as $row => $line ) {
		$len = strlen( $line );
		for ( $col = 0; $col < $len; $col++ ) {
			if ( '#' === $line[ $col ] ) {
				printf( '<circle cx="%d" cy="%d" r="1.3"/>', $col * $mc_step + 2, $row * $mc_step + 2 );
			}
		}
	}
	?>
</svg>
